export function isCspUniverseSymbol(symbol: string): boolean {
  const s = symbol.trim().toUpperCase();
  if (!s || DROP.has(s) || ADR.has(s)) return false;
  return CSP_UNIVERSE.some((n) => n.symbol.toUpperCase() === s || n.yahoo.toUpperCase() === s);
}
